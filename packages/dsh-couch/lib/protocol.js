/**
 * dsh-couch tunnel protocol v1.
 *
 * One WebSocket carries a JSON control channel plus length-prefixed binary
 * stream frames. Both the self-hosted relay and the DSH plugin ship a copy of
 * this file; `scripts/sync-protocol.mjs` keeps the copies identical and the
 * test suite fails when they drift.
 *
 * Control frame:  UTF-8 JSON object with a `type` string.
 * Binary frame:   [1 byte kind][4 byte big-endian stream id][payload]
 *
 * Only the relay opens streams (phone HTTP requests / WebSocket upgrades);
 * the plugin answers on the same stream id. Control request ids are opaque
 * strings generated by the sender.
 */

/** Wire protocol version. The relay rejects any other version with 4002. */
export const PROTOCOL_VERSION = 1

/** Close codes used by both ends. */
export const CLOSE = {
  /** Normal shutdown. */
  NORMAL: 1000,
  /** The same tunnel id connected again; the older socket is retired. */
  REPLACED: 4001,
  /** Protocol version or frame contract mismatch. */
  PROTOCOL: 4002,
  /** Tunnel secret / registration token rejected. */
  UNAUTHORIZED: 4003,
  /** Relay capacity exhausted. */
  CAPACITY: 4004,
  /** Peer violated limits (size, stream count, malformed data). */
  LIMIT: 4008,
}

/** Binary frame kinds. */
export const KIND = {
  /** HTTP request body, relay -> plugin. */
  REQUEST_BODY: 1,
  /** HTTP response body, plugin -> relay. */
  RESPONSE_BODY: 2,
  /** WebSocket text message (UTF-8 bytes), either direction. */
  WS_TEXT: 3,
  /** WebSocket binary message, either direction. */
  WS_BINARY: 4,
}

/** Stable error codes shared by the wire, HTTP routes and the UI. */
export const ERROR = {
  BAD_REQUEST: 'bad-request',
  PROTOCOL: 'protocol-mismatch',
  UNAUTHORIZED: 'unauthorized',
  REPLACED: 'replaced',
  TUNNEL_LIMIT: 'tunnel-limit',
  REGISTER_TOKEN: 'register-token',
  PAIRING_BUSY: 'pairing-busy',
  PAIRING_EXPIRED: 'pairing-expired',
  PAIRING_CANCELLED: 'pairing-cancelled',
  PAIRING_USED: 'pairing-used',
  BAD_CODE: 'bad-code',
  TOO_MANY_ATTEMPTS: 'too-many-attempts',
  ALREADY_PAIRED: 'already-paired',
  DEVICE_NOT_FOUND: 'device-not-found',
  STREAM_LIMIT: 'stream-limit',
  STREAM_TIMEOUT: 'stream-timeout',
  UPSTREAM_UNREACHABLE: 'upstream-unreachable',
  TOO_LARGE: 'too-large',
  INTERNAL: 'internal',
}

/** Hard limits enforced by the codec. */
export const LIMITS = {
  CONTROL_BYTES: 1024 * 1024,
  HTTP_BODY_CHUNK_BYTES: 64 * 1024,
  WS_MESSAGE_BYTES: 8 * 1024 * 1024,
  STREAM_WINDOW_BYTES: 512 * 1024,
  MAX_STREAMS_PER_TUNNEL: 64,
  MAX_HEADER_BYTES: 32 * 1024,
  MAX_URL_BYTES: 8 * 1024,
}

const HTTP_KINDS = new Set([KIND.REQUEST_BODY, KIND.RESPONSE_BODY])
const WS_KINDS = new Set([KIND.WS_TEXT, KIND.WS_BINARY])
const TYPE_PATTERN = /^[a-z0-9][a-z0-9.-]{0,63}$/u

/** Thrown for any malformed or oversized wire value. */
export class ProtocolError extends Error {
  /**
   * @param {string} code stable {@link ERROR} code
   * @param {string} message human-readable detail
   */
  constructor(code, message) {
    super(message)
    this.name = 'ProtocolError'
    this.code = code
  }
}

/**
 * @param {unknown} value
 * @returns {value is Record<string, unknown>}
 */
export function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/**
 * Encode one control message as WebSocket text.
 * @param {Record<string, unknown>} message
 * @returns {string}
 */
export function encodeControl(message) {
  if (!isRecord(message)) throw new ProtocolError(ERROR.BAD_REQUEST, 'control message must be an object')
  const { type } = message
  if (typeof type !== 'string' || !TYPE_PATTERN.test(type)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'control message type is invalid')
  }
  let text
  try {
    text = JSON.stringify(message)
  } catch {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'control message is not JSON serializable')
  }
  if (Buffer.byteLength(text, 'utf8') > LIMITS.CONTROL_BYTES) {
    throw new ProtocolError(ERROR.TOO_LARGE, 'control message exceeds the size limit')
  }
  return text
}

/**
 * Decode one WebSocket text frame.
 * @param {string} text
 * @returns {Record<string, unknown> & { type: string }}
 */
export function decodeControl(text) {
  if (typeof text !== 'string') throw new ProtocolError(ERROR.BAD_REQUEST, 'control frame must be text')
  if (Buffer.byteLength(text, 'utf8') > LIMITS.CONTROL_BYTES) {
    throw new ProtocolError(ERROR.TOO_LARGE, 'control frame exceeds the size limit')
  }
  let parsed
  try {
    parsed = JSON.parse(text)
  } catch {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'control frame is not JSON')
  }
  if (!isRecord(parsed)) throw new ProtocolError(ERROR.BAD_REQUEST, 'control frame must be an object')
  const { type } = parsed
  if (typeof type !== 'string' || !TYPE_PATTERN.test(type)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'control frame type is invalid')
  }
  return /** @type {Record<string, unknown> & { type: string }} */ (parsed)
}

/**
 * Encode one binary stream frame.
 * @param {number} kind one of {@link KIND}
 * @param {number} streamId positive 32-bit integer
 * @param {Uint8Array} payload
 * @returns {Buffer}
 */
export function encodeBinary(kind, streamId, payload) {
  if (!HTTP_KINDS.has(kind) && !WS_KINDS.has(kind)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, `unknown binary kind ${String(kind)}`)
  }
  if (!Number.isInteger(streamId) || streamId <= 0 || streamId > 0xffffffff) {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'stream id is invalid')
  }
  if (!(payload instanceof Uint8Array)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'binary payload must be bytes')
  }
  const max = HTTP_KINDS.has(kind) ? LIMITS.HTTP_BODY_CHUNK_BYTES : LIMITS.WS_MESSAGE_BYTES
  if (payload.byteLength > max) {
    throw new ProtocolError(ERROR.TOO_LARGE, 'binary payload exceeds the size limit')
  }
  const frame = Buffer.allocUnsafe(5 + payload.byteLength)
  frame.writeUInt8(kind, 0)
  frame.writeUInt32BE(streamId, 1)
  frame.set(payload, 5)
  return frame
}

/**
 * Decode one binary stream frame.
 * @param {Uint8Array} frame
 * @returns {{ kind: number, streamId: number, payload: Buffer }}
 */
export function decodeBinary(frame) {
  if (!(frame instanceof Uint8Array)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, 'binary frame must be bytes')
  }
  if (frame.byteLength < 5) throw new ProtocolError(ERROR.BAD_REQUEST, 'binary frame is truncated')
  const kind = frame[0]
  if (!HTTP_KINDS.has(kind) && !WS_KINDS.has(kind)) {
    throw new ProtocolError(ERROR.BAD_REQUEST, `unknown binary kind ${String(kind)}`)
  }
  const streamId = Buffer.from(frame.buffer, frame.byteOffset, frame.byteLength).readUInt32BE(1)
  if (streamId === 0) throw new ProtocolError(ERROR.BAD_REQUEST, 'stream id is invalid')
  const payload = Buffer.from(frame.buffer, frame.byteOffset + 5, frame.byteLength - 5)
  const max = HTTP_KINDS.has(kind) ? LIMITS.HTTP_BODY_CHUNK_BYTES : LIMITS.WS_MESSAGE_BYTES
  if (payload.byteLength > max) {
    throw new ProtocolError(ERROR.TOO_LARGE, 'binary payload exceeds the size limit')
  }
  return { kind, streamId, payload }
}

/**
 * Build one canonical error control message.
 * @param {string} code
 * @param {string} message
 * @param {Record<string, unknown>} [extra]
 */
export function errorMessage(code, message, extra = {}) {
  return { type: 'error', code, message, ...extra }
}

/**
 * @param {unknown} value
 * @returns {value is string}
 */
export function nonEmptyString(value) {
  return typeof value === 'string' && value.length > 0
}
